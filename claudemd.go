package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// ============================================================================
// Claude Code integration: the always-loaded part.
//
// zvk generates ONE file, <root>/CLAUDE.md, and injects exactly ONE `@import`
// of it into the user's global ~/.claude/CLAUDE.md. Everything in that file is
// loaded into every Claude Code session, relevant or not, so it is kept to a
// few lines:
//
//   - Sections are written inline. There are no nested per-feature imports;
//     each imported file costs an extra provenance header in the context.
//   - Notes for humans ("generated, do not edit") go in a block-level HTML
//     comment, which Claude Code strips before injecting the file.
//   - Only docs needed whenever their tool is used belong here (the zig
//     command/version rule). Situational features (fetch, serve) are skills,
//     loaded on demand (see claudeskill.go).
//
// refreshZvkClaudeMd is called after anything that changes a section (zig
// install, self-install). It also migrates older layouts: per-feature
// <root>/<feature>/CLAUDE.md files and their global imports are removed. When
// no section has content, the file and its global import are removed.
//
// Gated by ZVK_NO_DOCS (skip everything) / ZVK_NO_CLAUDE_MD (write the file
// but don't touch the global one).
// ============================================================================

const zvkClaudeMdHeader = "<!-- Generated by zvk; do not edit (rewritten by zvk commands). Disable with ZVK_NO_CLAUDE_MD=1. -->\n"

// claudeMdSections are the inline sections of <root>/CLAUDE.md, in order. A
// section returns "" when it has nothing to say.
var claudeMdSections = []func(absRoot string) string{
	zigClaudeSection,
}

func refreshZvkClaudeMd(root string, stdout io.Writer) {
	if os.Getenv("ZVK_NO_DOCS") != "" {
		return
	}
	absRoot, err := filepath.Abs(root)
	if err != nil {
		absRoot = root
	}
	// Older zvk versions imported this per-feature doc from the aggregate.
	os.Remove(filepath.Join(absRoot, "zig", "CLAUDE.md"))

	var b strings.Builder
	b.WriteString(zvkClaudeMdHeader)
	any := false
	for _, section := range claudeMdSections {
		if text := section(absRoot); text != "" {
			b.WriteString("\n" + text)
			any = true
		}
	}
	aggPath := filepath.Join(absRoot, "CLAUDE.md")
	if !any {
		if err := os.Remove(aggPath); err != nil && !os.IsNotExist(err) {
			fmt.Fprintf(stdout, "[zvk] note: could not remove %s: %v\n", aggPath, err)
		}
		if os.Getenv("ZVK_NO_CLAUDE_MD") == "" {
			if err := syncAggregateImport(absRoot, aggPath, false); err != nil {
				fmt.Fprintf(stdout, "[zvk] note: could not update ~/.claude/CLAUDE.md: %v\n", err)
			}
		}
		return
	}
	if err := writeFileAtomic(aggPath, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(stdout, "[zvk] note: could not write %s: %v\n", aggPath, err)
		return
	}
	if os.Getenv("ZVK_NO_CLAUDE_MD") != "" {
		return
	}
	if err := syncAggregateImport(absRoot, aggPath, true); err != nil {
		fmt.Fprintf(stdout, "[zvk] note: could not link CLAUDE.md into ~/.claude/CLAUDE.md: %v\n", err)
	}
}

// syncAggregateImport removes every zvk-injected line from ~/.claude/CLAUDE.md:
// the aggregate import itself (idempotent re-run) and legacy per-feature imports
// under <root>, along with the "# Added by zvk" markers that preceded them. With
// add, it then appends the aggregate import exactly once. The file is rewritten
// only when its content changes, and never created just to remove lines.
func syncAggregateImport(root, aggPath string, add bool) error {
	home, err := os.UserHomeDir()
	if err != nil {
		return err
	}
	globalPath := filepath.Join(home, ".claude", "CLAUDE.md")
	existing, err := os.ReadFile(globalPath)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err != nil && !add {
		return nil
	}

	importLine := "@" + aggPath
	rootPrefix := "@" + root + string(filepath.Separator)

	var kept []string
	for _, ln := range strings.Split(string(existing), "\n") {
		t := strings.TrimSpace(ln)
		switch {
		case t == "# Added by zvk":
			continue
		case t == importLine:
			continue
		case strings.HasPrefix(t, rootPrefix) && strings.HasSuffix(t, "CLAUDE.md"):
			// Legacy per-feature import (@<root>/<feature>/CLAUDE.md).
			continue
		}
		kept = append(kept, ln)
	}
	for len(kept) > 0 && strings.TrimSpace(kept[len(kept)-1]) == "" {
		kept = kept[:len(kept)-1]
	}

	buf := strings.Join(kept, "\n")
	if len(buf) > 0 {
		buf += "\n"
	}
	if add {
		buf += "\n# Added by zvk\n" + importLine + "\n"
	}
	if buf == string(existing) {
		return nil
	}

	if err := os.MkdirAll(filepath.Dir(globalPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(globalPath, []byte(buf), 0o644)
}
