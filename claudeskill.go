package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// ============================================================================
// Claude Code skills for the non-toolchain features (`zvk fetch`, `zvk serve`).
//
// A CLAUDE.md @import is loaded into every session in full, whether or not the
// feature is relevant. A skill costs only its one-line description until Claude
// Code decides it applies, then the body loads on demand. fetch and serve are
// situational (anti-bot pages, sharing a report), so self-install writes them as
// ~/.claude/skills/zvk-<feature>/SKILL.md. The zig decision table stays in the
// CLAUDE.md aggregate (see claudemd.go): it is short and needed whenever Zig
// is written.
//
// Ownership: zvk only overwrites a SKILL.md that carries zvkSkillMarker, so a
// user-authored skill with the same name is left alone.
//
// Gated by ZVK_NO_DOCS / ZVK_NO_CLAUDE_MD (either one skips writing into
// ~/.claude). Best-effort: failures print an advisory and never fail install.
// ============================================================================

const zvkSkillMarker = "<!-- Generated by zvk; overwritten by `zvk self-install`. -->"

// legacyFeatureDocs are <root>/<feature>/CLAUDE.md files written by zvk
// versions that @import'ed fetch/serve docs; they are removed on self-install.
var legacyFeatureDocs = []string{"fetch", "serve"}

type claudeSkill struct {
	name        string
	description string // single line; decides when Claude Code loads the body
	body        string
}

func zvkSkills() []claudeSkill {
	return []claudeSkill{fetchSkill(), serveSkill()}
}

// installClaudeSkills writes zvk's skills, removes legacy per-feature
// CLAUDE.md docs, and rebuilds the aggregate so it no longer imports them.
func installClaudeSkills(root string, stdout io.Writer) {
	absRoot, err := filepath.Abs(root)
	if err != nil {
		absRoot = root
	}
	for _, feature := range legacyFeatureDocs {
		dir := filepath.Join(absRoot, feature)
		if err := os.Remove(filepath.Join(dir, "CLAUDE.md")); err != nil && !os.IsNotExist(err) {
			fmt.Fprintf(stdout, "[zvk] note: could not remove legacy %s/CLAUDE.md: %v\n", feature, err)
		}
		os.Remove(dir) // only succeeds if now empty
	}
	refreshZvkClaudeMd(absRoot, stdout)

	if os.Getenv("ZVK_NO_DOCS") != "" || os.Getenv("ZVK_NO_CLAUDE_MD") != "" {
		return
	}
	skillsDir, err := claudeSkillsDir()
	if err != nil {
		fmt.Fprintf(stdout, "[zvk] note: could not locate Claude Code skills dir: %v\n", err)
		return
	}
	for _, s := range zvkSkills() {
		path, err := writeClaudeSkill(skillsDir, s)
		if err != nil {
			fmt.Fprintf(stdout, "[zvk] note: skill %s not written: %v\n", s.name, err)
			continue
		}
		fmt.Fprintf(stdout, "[zvk] Claude Code skill written to %s\n", path)
	}
}

func claudeSkillsDir() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, ".claude", "skills"), nil
}

// writeClaudeSkill writes <skillsDir>/<name>/SKILL.md, refusing to replace a
// file zvk did not generate.
func writeClaudeSkill(skillsDir string, s claudeSkill) (string, error) {
	path := filepath.Join(skillsDir, s.name, "SKILL.md")
	existing, err := os.ReadFile(path)
	switch {
	case err == nil && !strings.Contains(string(existing), zvkSkillMarker):
		return "", fmt.Errorf("%s exists and was not generated by zvk", path)
	case err != nil && !os.IsNotExist(err):
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	return path, writeFileAtomic(path, []byte(s.render()), 0o644)
}

func (s claudeSkill) render() string {
	return "---\n" +
		"name: " + s.name + "\n" +
		"description: " + s.description + "\n" +
		"---\n\n" +
		zvkSkillMarker + "\n\n" +
		s.body
}

func fetchSkill() claudeSkill {
	return claudeSkill{
		name: "zvk-fetch",
		description: "Fetch a URL with a real Chrome TLS and HTTP/2 fingerprint via `zvk fetch`. " +
			"Use when WebFetch, curl or a script gets a Cloudflare/Akamai/anti-bot challenge, " +
			"a 403 or 503, an empty body, or an \"enable JavaScript\" wall.",
		body: "# zvk fetch\n\n" +
			"`zvk fetch <url>` impersonates " + profileLabel("") + " at the TLS ClientHello,\n" +
			"HTTP/2 SETTINGS and header-order level, which anti-bot edges check and\n" +
			"WebFetch/curl fail. Access is not guaranteed. It does NOT run JavaScript:\n" +
			"client-rendered SPAs return their raw HTML shell.\n\n" +
			"```sh\n" +
			"zvk fetch https://example.com                 # body to stdout\n" +
			"zvk fetch -i https://example.com              # include response headers\n" +
			"zvk fetch -o page.html https://example.com    # write body to a file\n" +
			"zvk fetch -X POST -H 'Content-Type: application/json' \\\n" +
			"  -d '{\"q\":1}' https://api.example.com/v1     # JSON POST\n" +
			"zvk fetch --profile chrome_154 <url>          # a specific profile\n" +
			"zvk fetch --list-profiles                     # all profiles + the default\n" +
			"```\n\n" +
			"Status goes to stderr (`-s` silences it); stdout is only the body. Override\n" +
			"headers with `-A` (User-Agent) and `-H`.\n",
	}
}

func serveSkill() claudeSkill {
	return claudeSkill{
		name: "zvk-serve",
		description: "Share a generated file or HTML report over HTTP with `zvk serve` " +
			"(prints local and LAN URLs), or receive files uploaded from another machine " +
			"with `zvk serve --receive`. Use when the user wants to open a generated report " +
			"in a browser, share it on the LAN, or transfer files between machines.",
		body: "# zvk serve\n\n" +
			"`zvk serve` blocks until stopped: always run it in the background, then give\n" +
			"the user the URL it prints.\n\n" +
			"```sh\n" +
			"zvk serve report.html        # serves only this file (siblings stay private)\n" +
			"zvk serve ./site/            # serves a directory\n" +
			"zvk serve --local report.html   # bind 127.0.0.1 only (default: LAN too)\n" +
			"```\n\n" +
			"Output: `[zvk serve] local: http://127.0.0.1:8000/report.html` and a `LAN:` line.\n\n" +
			"## Receiving uploads\n\n" +
			"```sh\n" +
			"zvk serve --receive out.bin --once   # one POST/PUT body into out.bin, then exit\n" +
			"zvk serve --receive ./inbox/         # each upload → ./inbox/<name from URL>\n" +
			"# sender: curl -X POST --data-binary @file http://<host>:8000/name\n" +
			"```\n\n" +
			"Options: `-p <port>` (default 8000, falls back if taken), `--once` (exit after\n" +
			"the first successful transfer), `--max-bytes <n>` (upload cap, default 1 GiB,\n" +
			"0 = none), `-q` (no request log).\n",
	}
}
